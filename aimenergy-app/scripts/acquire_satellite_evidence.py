"""Reacquire only the bounded, licensed EOX demonstration crop using verified TLS.

Run from any directory. No credentials or third-party dependencies required.
The Google temporal series is intentionally not generated by this script.
"""
from pathlib import Path
import hashlib
import json
import urllib.request

ROOT = Path(__file__).resolve().parents[1]

def main():
    evidence = json.loads((ROOT / 'dist/data/satellite-evidence.json').read_text())
    imagery = evidence['sites'][0]['imagery']
    request = urllib.request.Request(imagery['request_url'], headers={'User-Agent': 'AimEnergy research demonstration'})
    with urllib.request.urlopen(request, timeout=60) as response:
        if response.headers.get_content_type() != 'image/jpeg':
            raise ValueError('WMS did not return JPEG')
        data = response.read(2_000_001)
    if len(data) > 2_000_000 or not data.startswith(b'\xff\xd8'):
        raise ValueError('Invalid or unexpectedly large bounded crop')
    digest = hashlib.sha256(data).hexdigest()
    if digest != imagery['sha256']:
        raise ValueError('Source changed; review provenance before replacing the audited image')
    for output in [ROOT / 'Data/raw/satellite/orii-gangodye-eox-2024.jpg', ROOT / 'dist/images/satellite-orii-gangodye-2024.jpg']:
        output.write_bytes(data)
    print('Verified historical crop:', digest)

if __name__ == '__main__':
    main()
